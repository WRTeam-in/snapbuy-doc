/**
 * Generates offline-docs/offline.css from src/css/custom.css.
 *
 * The live stylesheet pulls Plus Jakarta Sans and JetBrains Mono from
 * fonts.googleapis.com. In an offline copy those requests fail and the browser
 * stalls on them, so every remote @import is stripped and replaced with a
 * self-contained system font stack. Nothing in src/ is modified.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OFFLINE_DIR = path.resolve(HERE, "..");
const PROJECT_ROOT = path.join(path.resolve(OFFLINE_DIR, ".."), "snapbuy-doc");

const SOURCE = path.join(PROJECT_ROOT, "src", "css", "custom.css");
const TARGET = path.join(OFFLINE_DIR, "offline.css");

const REMOTE_IMPORT = /^\s*@import\s+url\(\s*['"]?https?:\/\/[^)]*\)\s*;\s*$/gim;

const SYSTEM_SANS =
  "system-ui, -apple-system, 'Segoe UI', Roboto, 'Helvetica Neue', Arial, sans-serif";
const SYSTEM_MONO =
  "ui-monospace, SFMono-Regular, 'SF Mono', Menlo, Consolas, 'Liberation Mono', monospace";

function main() {
  if (!fs.existsSync(SOURCE)) {
    console.error(`[offline] Source stylesheet not found: ${SOURCE}`);
    process.exit(1);
  }

  const original = fs.readFileSync(SOURCE, "utf8");
  const stripped = original.replace(REMOTE_IMPORT, "");
  const removed = (original.match(REMOTE_IMPORT) || []).length;

  const header = `/**
 * AUTO-GENERATED — do not edit.
 * Source: src/css/custom.css
 * Generated by offline-docs/scripts/prepare-offline-css.mjs
 *
 * ${removed} remote @import rule(s) removed for offline use.
 */

`;

  const footer = `

/* ══════════════════════════════════════════════════════════════════════════
   OFFLINE FONT FALLBACK
   The webfonts are unavailable without a network, so pin the variables to
   fonts that ship with the operating system.
   ══════════════════════════════════════════════════════════════════════════ */

:root,
[data-theme='dark'],
[data-theme='light'] {
  --ifm-font-family-base: ${SYSTEM_SANS};
  --ifm-heading-font-family: ${SYSTEM_SANS};
  --ifm-font-family-monospace: ${SYSTEM_MONO};
}
`;

  fs.writeFileSync(TARGET, header + stripped + footer, "utf8");
  console.log(
    `[offline] offline.css written (${removed} remote @import rule(s) removed).`
  );
}

main();
